let _i18nLang = null;
window.getLang = getLang;
window.setLang = setLang;

function _i18nDetectLang() {
  try {
    const saved = localStorage.getItem('pdb_lang');
    if (saved && I18N_LOCALES[saved]) return saved;
    const nav = (navigator.language || 'ru').slice(0, 2).toLowerCase();
    if (I18N_LOCALES[nav]) return nav;
    return 'ru';
  } catch (e) { return 'ru'; }
}

function getLang() {
  if (!_i18nLang) _i18nLang = _i18nDetectLang();
  return _i18nLang;
}

function t(key, params) {
  const lang = getLang();
  const dict = I18N_LOCALES[lang] || I18N_LOCALES.ru;
  let s = dict[key];
  if (s == null) s = I18N_LOCALES.ru[key];
  if (s == null) s = key;
  if (params) {
    for (const k in params) {
      if (Object.prototype.hasOwnProperty.call(params, k)) {
        s = s.split('{' + k + '}').join(String(params[k]));
      }
    }
  }
  return s;
}

function setLang(lang) {
  if (!I18N_LOCALES[lang]) return;
  _i18nLang = lang;
  try { localStorage.setItem('pdb_lang', lang); } catch (e) {}
  document.documentElement.setAttribute('lang', lang);
  applyI18nToDOM();
  try {
    if (typeof updateSectionUI === 'function') updateSectionUI();
    if (typeof updateProgress === 'function') updateProgress();
    if (typeof applyFiltersAndRender === 'function') applyFiltersAndRender();
    if (typeof renderTagFilter === 'function') renderTagFilter();
    if (typeof renderTagsManager === 'function') renderTagsManager();
    if (typeof renderTagChips === 'function') renderTagChips();
    if (typeof updateCurrentProjectInfo === 'function') updateCurrentProjectInfo();
    if (typeof isModalOpen === 'function') {
      if (isModalOpen('settingsModal')) {
        if (typeof _refreshStorageInfo === 'function') _refreshStorageInfo();
        if (typeof _refreshFfmpegStatus === 'function') _refreshFfmpegStatus();
        if (typeof loadModelsIntoUI === 'function') loadModelsIntoUI().catch(() => {});
      }
      if (isModalOpen('logsModal') && typeof refreshLogs === 'function') refreshLogs(true);
    }
  } catch (e) { console.warn('i18n: redraw failed', e); }
  try {
    window.dispatchEvent(new CustomEvent('pdb-lang-change', { detail: { lang } }));
  } catch (e) {}
}

function applyI18nToDOM(root) {
  const scope = root || document;
  if (scope.nodeType === 1 && scope.hasAttribute && scope.hasAttribute('data-i18n')) {
    scope.textContent = t(scope.getAttribute('data-i18n'));
  }
  if (scope.nodeType === 1 && scope.hasAttribute && scope.hasAttribute('data-i18n-title')) {
    scope.setAttribute('title', t(scope.getAttribute('data-i18n-title')));
  }
  if (scope.nodeType === 1 && scope.hasAttribute && scope.hasAttribute('data-i18n-aria-label')) {
    scope.setAttribute('aria-label', t(scope.getAttribute('data-i18n-aria-label')));
  }
  if (scope.nodeType === 1 && scope.hasAttribute && scope.hasAttribute('data-i18n-placeholder')) {
    scope.setAttribute('placeholder', t(scope.getAttribute('data-i18n-placeholder')));
  }
  if (!scope.querySelectorAll) return;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
}
