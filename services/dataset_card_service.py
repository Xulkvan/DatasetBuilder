"""[STAGE2:dataset_card] README.md с распределением классов и bbox."""
from __future__ import annotations

import os
from collections import Counter
from statistics import mean

from sqlalchemy.orm import Session
from sqlalchemy import func

from models import Project, ImageModel, Annotation


def generate_dataset_card(db: Session, project_id: int) -> str:
    proj = db.query(Project).filter(Project.id == project_id).first()
    if not proj:
        return "# Dataset\n\n*(project not found)*\n"

    imgs = (db.query(ImageModel)
              .filter(ImageModel.project_id == project_id,
                      ImageModel.is_deleted.is_(False)).all())
    anns = (db.query(Annotation)
              .join(ImageModel, Annotation.image_id == ImageModel.id)
              .filter(ImageModel.project_id == project_id,
                      ImageModel.is_deleted.is_(False)).all())

    label_counts = Counter(a.label for a in anns)
    beh_counts = Counter(a.behavior for a in anns if a.behavior)
    bbox_areas = [a.w * a.h for a in anns if a.w and a.h]
    bbox_sizes = [(a.w, a.h) for a in anns if a.w and a.h]

    lines = []
    lines.append(f"# Dataset: {proj.name}\n")
    lines.append(f"**Object class:** `{proj.object_class or 'pig'}`  ")
    lines.append(f"**Random seed:** `{getattr(proj, 'random_seed', 42)}`  ")
    lines.append(f"**Images:** {len(imgs)}  ")
    lines.append(f"**Annotations:** {len(anns)}  ")
    annotated_imgs = len({a.image_id for a in anns})
    lines.append(f"**Annotated images:** {annotated_imgs}/{len(imgs)}  ")
    lines.append("\n")

    if label_counts:
        lines.append("## Class distribution\n")
        lines.append("| Label | Count |")
        lines.append("|-------|-------|")
        for lbl, cnt in label_counts.most_common():
            lines.append(f"| {lbl} | {cnt} |")
        lines.append("\n")

    if beh_counts:
        lines.append("## Behavior distribution\n")
        lines.append("| Behavior | Count |")
        lines.append("|----------|-------|")
        for b, c in beh_counts.most_common():
            lines.append(f"| {b} | {c} |")
        lines.append("\n")

    if bbox_areas:
        avg_w = mean(w for w, _ in bbox_sizes)
        avg_h = mean(h for _, h in bbox_sizes)
        avg_a = mean(bbox_areas)
        lines.append("## Bounding box statistics (normalized 0..1)\n")
        lines.append(f"- **Mean width:** {avg_w:.4f}")
        lines.append(f"- **Mean height:** {avg_h:.4f}")
        lines.append(f"- **Mean area:** {avg_a:.4f}")
        lines.append("\n")

    lines.append("---\n")
    lines.append("*Generated by DatasetBuilder*\n")
    return "\n".join(lines)
